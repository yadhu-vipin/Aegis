#[test]
fn benign_pdf_is_released() {
    let Some(o) = scan(
        "benign_document.pdf",
        "aaaaaaaa-0000-4000-8000-000000000001",
        "benign_document.pdf",
    ) else {
        eprintln!("{SKIP}");
        return;
    };
    assert_eq!(
        o.status, "COMPLETE",
        "an ordinary PDF must be released: {}",
        o.verdict
    );
}

/// The single most important regression guard in the suite.
///
/// An archive containing source code, documentation and a licence is what most
/// downloaded archives are. If archive inspection ever starts blocking this,
/// it has become a false-positive generator.
#[test]
fn ordinary_source_archive_is_released() {
    let Some(o) = scan(
        "ordinary_project.zip",
        "aaaaaaaa-0000-4000-8000-000000000002",
        "ordinary_project.zip",
    ) else {
        eprintln!("{SKIP}");
        return;
    };
    assert_eq!(
        o.status, "COMPLETE",
        "an ordinary source archive must be released: {}",
        o.verdict
    );
}

/// A binary signed by Microsoft must be released, and the user should be told
/// who signed it.
///
/// Most Windows binaries carry no *embedded* signature — they are covered by a
/// signed system catalogue — so this exercises the catalogue path, which is
/// exactly the one an embedded-only check gets wrong by calling `notepad.exe`
/// unsigned.
#[test]
fn signed_windows_binary_is_released_and_names_its_publisher() {
    let Some(o) = scan(
        "signed_windows_binary.exe",
        "aaaaaaaa-0000-4000-8000-000000000003",
        "signed_windows_binary.exe",
    ) else {
        eprintln!("{SKIP}");
        return;
    };

    assert_eq!(
        o.status, "COMPLETE",
        "a Microsoft-signed Windows binary must be released: {}",
        o.verdict
    );

    let text = o.user_visible_text().to_lowercase();
    assert!(
        text.contains("signed") || text.contains("catalog") || text.contains("catalogue"),
        "provenance was verified but never shown to the user. This is the whole \
         user-visible payoff of Authenticode, and it only ever appears on files \
         that PASS. verdict={:?} findings={:?}",
        o.verdict,
        o.findings
    );
}

