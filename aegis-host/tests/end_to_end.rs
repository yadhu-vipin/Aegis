//! The six cases from HANDOVER section 6, driven through the real host.
//!
//! These spawn `aegis-host.exe`, speak the native-messaging protocol to it over
//! a pipe, and place real files in the real quarantine directory — the same
//! path the browser writes to. The only part of the production flow not
//! exercised here is the browser itself deciding to call
//! `onDeterminingFilename`.
//!
//! ## Why this file exists separately from `ipc_roundtrip.rs`
//!
//! That file tests the protocol: malformed frames, paths outside the
//! quarantine root, the retired chunk protocol. This one tests the *verdicts* —
//! whether Aegis reaches the right conclusion about a realistic file, and
//! whether it says something a person could act on.
//!
//! ## Half of these assert that files are RELEASED
//!
//! That is deliberate and it is the half more likely to catch a regression.
//! Every check added to Aegis is a fresh chance to start blocking ordinary
//! downloads, and a scanner that blocks everything is indistinguishable from a
//! broken one — except that the broken one is more honest about it.
//!
//! ## Fixtures
//!
//! Generated by `scripts/make_test_files.py`, not committed: several are
//! deliberately malicious-looking and a repository full of things that trip
//! antivirus scanners is its own problem. Tests skip cleanly when a fixture is
//! absent, because a test that could not run must never be confused with one
//! that passed.
//!
//! There is deliberately no EICAR. On a machine with Defender running it
//! measures Defender, not Aegis.

use std::io::{Read, Write};
use std::path::PathBuf;
use std::process::{Command, Stdio};

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("aegis-host has a parent")
        .to_path_buf()
}

fn downloads_dir() -> PathBuf {
    #[cfg(windows)]
    let home = std::env::var("USERPROFILE").unwrap_or_default();
    #[cfg(not(windows))]
    let home = std::env::var("HOME").unwrap_or_default();
    PathBuf::from(home).join("Downloads")
}

fn frame(value: &serde_json::Value) -> Vec<u8> {
    let json = serde_json::to_vec(value).expect("serialize");
    let mut out = (json.len() as u32).to_le_bytes().to_vec();
    out.extend_from_slice(&json);
    out
}

fn parse_frames(buf: &[u8]) -> Vec<serde_json::Value> {
    let mut out = Vec::new();
    let mut pos = 0usize;
    while pos + 4 <= buf.len() {
        let len =
            u32::from_le_bytes([buf[pos], buf[pos + 1], buf[pos + 2], buf[pos + 3]]) as usize;
        pos += 4;
        if pos + len > buf.len() {
            break;
        }
        if let Ok(v) = serde_json::from_slice(&buf[pos..pos + len]) {
            out.push(v);
        }
        pos += len;
    }
    out
}

/// The outcome of putting one file through Aegis.
struct Outcome {
    status: String,
    verdict: String,
    findings: Vec<serde_json::Value>,
}

impl Outcome {
    /// Everything the user would be shown, flattened for searching.
    fn user_visible_text(&self) -> String {
        let mut s = self.verdict.clone();
        for f in &self.findings {
            for key in ["title", "why", "detail"] {
                if let Some(v) = f.get(key).and_then(|v| v.as_str()) {
                    s.push(' ');
                    s.push_str(v);
                }
            }
        }
        s
    }

    fn severities(&self) -> Vec<String> {
        self.findings
            .iter()
            .filter_map(|f| f.get("severity").and_then(|s| s.as_str()))
            .map(|s| s.to_string())
            .collect()
    }
}

/// Put `fixture` through the host as though the browser had just written it.
///
/// Returns `None` when the fixture or the Downloads directory is missing.
fn scan(fixture: &str, uuid: &str, presented_as: &str) -> Option<Outcome> {
    let source = repo_root().join("test_files").join(fixture);
    let content = std::fs::read(&source).ok()?;

    let downloads = downloads_dir();
    let quarantine = downloads.join("aegis_quarantine");
    std::fs::create_dir_all(&quarantine).ok()?;

    // Mirror what Chromium does: UUID stem, browser-chosen extension.
    let ext = std::path::Path::new(presented_as)
        .extension()
        .and_then(|e| e.to_str())
        .unwrap_or("bin");
    let planted = quarantine.join(format!("{uuid}.{ext}"));
    std::fs::write(&planted, &content).ok()?;

    let input = frame(&serde_json::json!({
        "type": "WATCH_BEGIN",
        "session_id": uuid,
        "quarantine_path": planted.to_string_lossy(),
        "original_filename": presented_as,
    }));

    let mut child = Command::new(env!("CARGO_BIN_EXE_aegis-host"))
        .current_dir(repo_root())
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("spawn aegis-host");

    // Every I/O result is collected BEFORE any early return, so the child is
    // always waited on. Bailing out with `?` between spawn and wait would leave
    // a zombie process behind for each skipped fixture.
    let mut stdout = Vec::new();
    let mut stderr = String::new();
    let wrote = child.stdin.take().unwrap().write_all(&input);
    let read = child.stdout.take().unwrap().read_to_end(&mut stdout);
    let _ = child.stderr.take().unwrap().read_to_string(&mut stderr);
    let _ = child.wait();
    wrote.ok()?;
    read.ok()?;

    // Clean up both the quarantine copy and anything released.
    let _ = std::fs::remove_file(&planted);
    let _ = std::fs::remove_file(downloads.join(presented_as));

    assert!(
        !stderr.contains("panicked"),
        "host panicked scanning {fixture}: {stderr}"
    );

    let frames = parse_frames(&stdout);
    // The LAST verdict: an early block sends one mid-transfer and a final one
    // afterwards, and the final one is the outcome.
    let verdict = frames
        .iter()
        .rfind(|f| f.get("type").and_then(|t| t.as_str()) == Some("VERDICT"))?;

    Some(Outcome {
        status: verdict
            .get("status")
            .and_then(|s| s.as_str())
            .unwrap_or("")
            .to_string(),
        verdict: verdict
            .get("verdict")
            .and_then(|s| s.as_str())
            .unwrap_or("")
            .to_string(),
        findings: verdict
            .get("findings")
            .and_then(|f| f.as_array())
            .cloned()
            .unwrap_or_default(),
    })
}

const SKIP: &str = "fixture missing — run scripts/make_test_files.py";

