/// The case archive inspection was written for.
///
/// Every other check sees an ordinary file: the container is a well-formed ZIP,
/// its entropy is normal for compressed data, and `structure.rs` deliberately
/// does not flag executables inside archives.
#[test]
fn archive_hiding_a_disguised_executable_is_blocked() {
    let Some(o) = scan(
        "invoice_archive.zip",
        "aaaaaaaa-0000-4000-8000-000000000004",
        "invoice_archive.zip",
    ) else {
        eprintln!("{SKIP}");
        return;
    };

    assert_ne!(
        o.status, "COMPLETE",
        "a ZIP containing invoice.pdf.exe must not be delivered: {}",
        o.verdict
    );
    assert!(
        o.user_visible_text().contains("invoice.pdf.exe"),
        "the verdict must name the entry responsible. Telling someone their \
         download was blocked without saying which file caused it leaves them \
         unable to judge whether the block was right. verdict={:?} findings={:?}",
        o.verdict,
        o.findings
    );
}

/// An executable wearing an image extension must not be delivered.
///
/// This is the canonical case and it guards the recalibration that let
/// `notepad.exe` through. String matches were capped well below the block
/// threshold because API names in a *program* mean nothing — but in a file
/// claiming to be a JPEG they are exactly the corroboration that matters, and
/// `deep_forensic_scan` adds them to the magic-byte mismatch for that reason.
///
/// If capping the strings ever silently disarms this, the cap went too far.
#[test]
fn executable_disguised_as_an_image_is_not_delivered() {
    let Some(o) = scan(
        "test_trojan.jpg",
        "aaaaaaaa-0000-4000-8000-000000000007",
        "holiday_photo.jpg",
    ) else {
        eprintln!("{SKIP}");
        return;
    };

    assert_ne!(
        o.status, "COMPLETE",
        "a program named .jpg must never be delivered: {}",
        o.verdict
    );

    let text = o.user_visible_text().to_lowercase();
    assert!(
        text.contains("not the type") || text.contains("claims") || text.contains("exe"),
        "the verdict must say the file is not what its name claims: {:?}",
        o.verdict
    );
}

/// An encrypted archive must be reported as UNSCANNABLE, never as clean.
///
/// Nothing can read inside it — not Aegis, not Defender — which is exactly why
/// malware campaigns ship password-protected archives with the password in the
/// email body. The decryption step moves to a human, past every automated check.
#[test]
fn encrypted_archive_is_reported_as_unscannable() {
    let Some(o) = scan(
        "protected_documents.zip",
        "aaaaaaaa-0000-4000-8000-000000000005",
        "protected_documents.zip",
    ) else {
        eprintln!("{SKIP}");
        return;
    };

    let text = o.user_visible_text().to_lowercase();
    assert!(
        text.contains("password") || text.contains("encrypted"),
        "an encrypted archive must be reported as unreadable rather than \
         silently treated as clean: status={} verdict={:?}",
        o.status,
        o.verdict
    );
}

/// A macro stream inside a format that cannot legitimately have one.
///
/// `.docx` is macro-free by definition, so `vbaProject.bin` inside one is a
/// mismatch nobody creates by accident. The same stream inside a `.docm` is
/// reported and not condemned — the user asked for a macro-enabled document.
#[test]
fn macro_in_a_macro_free_format_is_flagged() {
    let Some(o) = scan(
        "quarterly_report.docx",
        "aaaaaaaa-0000-4000-8000-000000000006",
        "quarterly_report.docx",
    ) else {
        eprintln!("{SKIP}");
        return;
    };

    let text = o.user_visible_text().to_lowercase();
    assert!(
        text.contains("macro"),
        "a macro inside a .docx must be reported: status={} verdict={:?} findings={:?}",
        o.status,
        o.verdict,
        o.findings
    );
    assert_ne!(
        o.status, "COMPLETE",
        "a macro in a macro-free format is a deliberate mismatch and must not \
         be delivered: {}",
        o.verdict
    );
}

