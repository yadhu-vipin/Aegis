/// A blocked file must arrive with an explanation a person can act on.
///
/// The verdict string alone is not enough. `finding.rs` exists because
/// `[risk=0.60] CreateRemoteThread (utf-8)` is accurate and useless to the
/// person whose download just vanished: it names an API without saying what the
/// file was trying to do or why they should care.
#[test]
fn blocked_files_carry_an_explanation_not_just_a_score() {
    for (fixture, uuid) in [
        ("invoice_archive.zip", "aaaaaaaa-0000-4000-8000-00000000000a"),
        ("quarterly_report.docx", "aaaaaaaa-0000-4000-8000-00000000000b"),
    ] {
        let Some(o) = scan(fixture, uuid, fixture) else {
            eprintln!("{SKIP}");
            return;
        };
        if o.status == "COMPLETE" {
            continue;
        }

        assert!(
            !o.findings.is_empty(),
            "{fixture} was blocked with no structured findings — the user gets a \
             refusal and no reason"
        );

        for f in &o.findings {
            for key in ["title", "why"] {
                let v = f.get(key).and_then(|v| v.as_str()).unwrap_or("");
                assert!(
                    !v.trim().is_empty(),
                    "{fixture}: a finding has an empty {key:?}, so part of the \
                     explanation renders blank: {f:?}"
                );
            }
        }

        assert!(
            !o.severities().is_empty(),
            "{fixture}: findings carry no severity, so the popup cannot order \
             them and a notification cannot pick the one that matters"
        );
    }
}

/// Nothing is ever left behind in quarantine.
///
/// A blocked file that stays on disk is a malicious file sitting in a
/// subdirectory of the user's Downloads folder, which is most of what Aegis
/// exists to prevent.
#[test]
fn quarantine_is_left_empty_whatever_the_verdict() {
    let downloads = downloads_dir();
    let quarantine = downloads.join("aegis_quarantine");
    if std::fs::create_dir_all(&quarantine).is_err() {
        return;
    }

    for (fixture, uuid) in [
        ("benign_document.pdf", "aaaaaaaa-0000-4000-8000-00000000000c"),
        ("invoice_archive.zip", "aaaaaaaa-0000-4000-8000-00000000000d"),
        ("protected_documents.zip", "aaaaaaaa-0000-4000-8000-00000000000e"),
    ] {
        if scan(fixture, uuid, fixture).is_none() {
            eprintln!("{SKIP}");
            return;
        }
        let leftover: Vec<_> = std::fs::read_dir(&quarantine)
            .into_iter()
            .flatten()
            .flatten()
            .filter(|e| e.file_name().to_string_lossy().starts_with(uuid))
            .collect();
        assert!(
            leftover.is_empty(),
            "{fixture} left {} file(s) in quarantine after the verdict",
            leftover.len()
        );
    }
}
